def replace_text_nodes(doc: Document, old: str, new: str) -> int:
    count = 0
    for node in doc.element.iter():
        if node.tag.endswith("}t") and node.text and old in node.text:
            node.text = node.text.replace(old, new)
            count += 1
    return count


def set_cell_paragraphs(cell, text: str) -> None:
    cell._tc.clear_content()
    for para in text.split("\n"):
        cell.add_paragraph(para)


